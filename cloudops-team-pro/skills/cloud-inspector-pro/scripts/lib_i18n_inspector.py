"""lib_i18n_inspector.py — cloud-inspector-pro 报告专用 UI 字符串表（本地，非跨团队）。

只放 inspector 报告自己的固定话术（表头 / 状态值 / 风险等级 / 叙述模板）。
跨团队的"标准枚举数据值"（云产品名 / 地域名 / 计费模式）仍走共享 i18n.tr()，
不要往这里塞产品名/地域名。

结构：
  · _ZH_KEYED_EN：用"中文原文"做 key 的 {中文: 英文}。zh 表自动取 {中文: 中文}，
    保证 L("zh", 中文) == 中文，zh 路径字节级不变。
  · _PAIRS：用语义标识做 key（report_title / cvm_coverage / 带占位符模板 …），
    显式给 ("中文", "英文") 两值，zh 值必须与改造前的字面量逐字一致。
  · L(lang, key, **kw)：取串后可选 .format(**kw) 填充命名占位符；
    缺失回退到 zh，再回退到 key 本身（绝不抛异常、绝不丢字）。
"""


def L(lang, key, **kw):
    table = STRINGS.get(lang, STRINGS["zh"])
    s = table.get(key, STRINGS["zh"].get(key, key))
    return s.format(**kw) if kw else s


