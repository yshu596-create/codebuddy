"""lib_i18n_resource.py — cloud-resource-pro 资源看板专用 UI 字符串表（本地，非跨团队）。

只放资源清点看板自己的固定话术（页面标题 / KPI 标签 / 表头 / 章节名 / 洞察模板）。
跨团队的"标准枚举数据值"（云产品名 / 地域中文名 / 计费模式）走共享 i18n.tr()，
不要往这里塞产品名/地域名。

约定（对齐 cloud-inspector-pro/lib_i18n_inspector.py）：
  · L(lang, key, **kw)：取串后可选 .format(**kw) 填充命名占位符；
    缺失回退到 zh，再回退到 key 本身（绝不抛异常、绝不丢字）。
  · zh 值必须是用户可见中文原文；en 值为对应英文。
  · output_lang 铁律：lang 决定全部 UI 文案语言，对话/概览/看板/PPT 四类必须一致。
"""


def L(lang, key, **kw):
    table = STRINGS.get(lang, STRINGS["zh"])
    s = table.get(key, STRINGS["zh"].get(key, key))
    return s.format(**kw) if kw else s


